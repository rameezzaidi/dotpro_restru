@register.simple_tag
def icon(name, size=18):
    inner = ICONS.get(name, "")
    return mark_safe(
        f'<svg class="ico" width="{size}" height="{size}" viewBox="0 0 24 24" fill="none" stroke="currentColor" '
        f'stroke-width="1.8" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">{inner}</svg>')


@register.simple_tag(takes_context=True)
def tr(context, text):
    return translate(text, context.get("lang", "en"))


@register.filter
def t(text, lang):
    return translate(text, lang)


@register.filter
def money(value, branch=None):
    try:
        v = Decimal(value or 0)
    except Exception:
        v = Decimal(0)
    sym = branch.currency_symbol if branch is not None and hasattr(branch, "currency_symbol") else current_currency()
    return f"{sym} {v:,.2f}"


@register.filter
def num(value):
    try:
        return f"{Decimal(value):,.3f}".rstrip("0").rstrip(".")
    except Exception:
        return value


@register.filter
def attr(obj, name):
    """Resolve dotted attribute / callable for generic tables."""
    for part in str(name).split("."):
        if obj is None:
            return ""
        obj = obj.get(part, "") if isinstance(obj, dict) else getattr(obj, part, "")
        if callable(obj):
            obj = obj()
    return obj


@register.filter
def getitem(d, key):
    try:
        return d.get(key)
    except Exception:
        return None


@register.simple_tag
def status_badge(order):
    cls = {"new": "b-blue", "preparing": "b-amber", "ready": "b-green", "served": "b-violet", "out_for_delivery": "b-violet",
           "completed": "b-grey", "cancelled": "b-red"}.get(order.status, "b-grey")
    if getattr(order, "acceptance", "") == "pending" and order.status == "new":
        return mark_safe('<span class="badge b-amber">Awaiting acceptance</span>')
    return format_html('<span class="badge {}">{}</span>', cls, order.get_status_display())


@register.simple_tag
def qr_svg(url, scale=3):
    """Inline SVG QR code (needs the 'segno' package; shows nothing if it is not installed)."""
    try:
        import segno
        from django.utils.safestring import mark_safe
        return mark_safe(segno.make(url, error="m").svg_inline(scale=scale, border=1, dark="#111"))
    except Exception:
        return ""
